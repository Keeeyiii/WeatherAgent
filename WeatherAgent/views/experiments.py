def render() -> None:
    hero(
        "实验总览",
        "七项实验，检验发现的稳健性与方法的边界",
    )

    st.warning("**科学发现不是最终结论，需要通过进一步实验检验。**")

    st.markdown(
        "下面每一项实验都按「研究问题 → 实验 → 结果 → 说明」组织；"
        "点击卡片底部的按钮进入详情页。"
    )

    for exp in EXPERIMENTS:
        with st.container(border=True):
            st.markdown(f"#### {exp['no']}｜{exp['title']}")
            st.markdown(f"**研究问题**　{exp['question']}")
            st.markdown(f"**实验**　{exp['experiment']}")
            st.markdown(f"**结果**　{exp['result']}")
            st.markdown(f"**说明**　{exp['meaning']}")
            if st.button(
                f"进入{exp['link']} →", key=f"goto_{exp['page']}_{exp['no']}", width="stretch"
            ):
                st.query_params["page"] = exp["page"]
                st.rerun()

    caption(
        "七项实验覆盖四条检验线：稳健性（①）、误差性质（②⑥）、"
        "订正能力与边界（③④⑤）、个例回放（⑦）。"
    )

"""局限与展望页：明确边界，记录被推翻的假设。"""

from __future__ import annotations

import streamlit as st

from views.common import caption, hero


def render() -> None:
    hero(
        "局限、边界与下一步",
        "一个研究项目的可信度，很大程度上取决于它是否清楚自己不知道什么",
    )

    st.subheader("已知局限")
    st.markdown(
        """
| 局限 | 对结论的影响 | 为什么目前无法解决 |
|---|---|---|
| 主站点只有南京，另有上海作对照 | 结论不能推广到全国；跨站点迁移已显示失效 | 中国境内免费逐小时地面观测覆盖有限 |
| 中国机场 METAR **不报降水量** | 无法开展降水检验（POD / FAR / TS 评分） | 实测 ZSNJ、ZSSS、ZSPD 的降水字段全为 0，需改用 IMERG / CHIRPS 等卫星产品 |
| 观测是机场站点，预报是格点值 | 存在代表性误差，可能贡献一部分偏差 | 需要模式的格点原始输出与站点下垫面信息 |
| 只检验 2 米气温 | 温度与降水的误差结构通常不同 | 受观测数据限制 |
| 时效数据仅覆盖最近 92 天 | 时效结论的季节代表性不足 | 免费归档只保留近三个月的历史预报运行 |
| 订正方法为纯统计后处理 | 缺乏物理约束，外推能力弱 | 这是统计订正公认的边界 |
        """
    )

    st.subheader("被数据推翻的假设")
    st.markdown(
        """
        研究过程中被否定掉的想法同样值得记录——它们说明结论是经过检验的，而不是预设的：

        1. ~~“订正的主要作用是消除系统偏差”~~
           → 常数去偏只改善 0.6%，因为全时段平均偏差本来就接近 0。
        2. ~~“按小时去偏就能抓住日变化的偏差”~~
           → 仅改善 0.9%，因为日变化偏差随季节改变符号。
        3. ~~“随机森林学到的订正关系可以推广到其他站点”~~
           → 迁移到上海后 MAE 反而变差 11.2%。
        4. ~~“模式误差主要由随机噪声构成”~~
           → 滞后 1 小时自相关 0.90，误差是与天气过程同步的慢变量。
        """
    )

    st.subheader("下一步")
    st.markdown(
        """
        **短期（数据可得、方法明确）**

        1. **把误差持续性作为预报因子**：用前 24 小时的观测误差作为随机森林输入，
           检验能否突破当前 22.8% 的改善上限。误差自相关 0.90 说明这里还有空间。
        2. **按天气型分组建模**：按风速、云量或环流型分组，
           检验“随天气状态变化的订正”是否优于固定查表。
        3. **增加第二、第三个站点**，把跨站点实验做成真正的泛化实验，
           量化“迁移损失随站点距离与气候差异如何变化”。

        **中期（需要更强的数据）**

        4. **接入卫星降水产品**（GPM IMERG / CHIRPS），把检验扩展到降水，
           计算 TS / ETS 等分类评分。
        5. **对比多个模式**（GFS / ECMWF / CMA），检验“振幅压缩”是某个模式的个性，
           还是全球模式的共性问题。
        6. **追踪物理过程**：获取模式的边界层高度、地表通量、云量等诊断量，
           直接检验振幅压缩与地气耦合之间的关联。

        **长期**

        7. 从“事后统计订正”走向“误差溯源”——理解模式为什么会产生这种误差结构，
           而不只是绕过它。
        """
    )

    st.subheader("这个项目最后想说什么")
    st.success(
        "**误差的平均值没有信息量，误差的结构才有。**\n\n"
        "一个规模不大的应用，如果能诚实地回答一个具体的小问题，"
        "并清楚地说明自己的边界在哪里，"
        "就比一个声称把准确率提高了 30%、却说不清这 30% 从何而来的系统更有价值。"
    )

    caption(
        "本页列出的每一条局限，都是本项目在实际运行中遇到并记录下来的，"
        "而不是事后补充的免责说明。"
    )

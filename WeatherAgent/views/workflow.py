"""分析工作流导引页：把研究问题翻译成一条分析路径。"""

from __future__ import annotations

import streamlit as st

from views.common import caption, hero

STEPS = [
    ("① 数据质量检查", "行数、必要字段、缺失值、重复、时间有效性、单位合理性——先确认数据可信。"),
    ("② 总体误差检验", "计算 bias / MAE / RMSE / 相关系数，给误差一个总体画像。"),
    ("③ 季节与日变化分解", "按月份、季节、一天中的时刻分组看误差，检查误差是不是一个固定的数。"),
    ("④ 振幅阻尼判据", "如果误差来自“模式响应不足”，日较差、距平响应、极端时刻会同时给出信号。"),
    ("⑤ 最低 / 最高气温分解", "把误差拆到日最低和日最高两侧，定位压缩落在哪一侧。"),
    ("⑥ 排除采样假象", "检查预报的时间分辨率，排除“比较方式造成的假象”。"),
    ("⑦ 误差持续性", "计算误差的自相关，判断误差是随机噪声，还是与天气过程同步的慢变量。"),
    ("⑧ 订正方法消融", "常数去偏、按小时去偏、线性回归、随机森林……逐层加结构，看收益来自哪里。"),
    ("⑨ 机器学习订正", "训练随机森林订正模型，滚动窗口交叉验证，检查特征重要性。"),
    ("⑩ 验证与泛化", "跨站点迁移、邻站同化、真实个例——检验结论和方法的边界。"),
]


def render() -> None:
    hero(
        "分析工作流",
        "从一个气象问题出发，逐步完成数据检查、误差诊断、结构分析和订正实验",
    )

    question = (st.session_state.get("user_question") or "").strip()
    if question:
        st.info(f"**当前研究问题**　{question}")
    else:
        st.info(
            "还没有设定研究问题——下面按默认问题展开。"
            "你可以回到 **🏠 研究问题** 页选择一个示例问题。"
        )

    st.subheader("AI 对这个问题的理解")
    st.markdown(
        f"""
        **你正在研究**　{question or "为什么天气预报会出错？"}

        **初步研究目标**　判断 GFS 预报的 2 米气温误差是否具有系统性，
        并进一步寻找误差随季节、昼夜和天气状态变化的规律——
        如果规律存在，再检验统计订正能在多大程度上利用这些规律。
        """
    )

    st.subheader("建议的分析路径")
    st.markdown(
        "下面这条路径对应右侧 **误差分析流水线** 页的六个步骤，"
        "也是本应用所有页面共同的骨架。"
    )
    for title, text in STEPS:
        st.markdown(f"- **{title}**　{text}")

    st.write("")
    if st.button("开始执行分析 →", key="run_analysis", type="primary", width="stretch"):
        st.query_params["page"] = "workflow-run"
        st.rerun()

    caption(
        "示例数据（南京 2.4 年）按这条路径跑完的完整结果，"
        "放在 **🧠 科学发现** 和 **🧪 验证与实验** 两个分区里。"
    )
